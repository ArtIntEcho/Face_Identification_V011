let currentLanguage = localStorage.getItem("face-access-language") || "zh";
const sourceText = new WeakMap();
const renderedText = new WeakMap();
const sourceAttributes = new WeakMap();

window.t = (source) => translations[currentLanguage]?.[source] || source;

function translateTextNode(node) {
  const current = node.nodeValue;
  if (current !== renderedText.get(node)) sourceText.set(node, current);
  const source = sourceText.get(node) || current;
  if (!source.trim()) return;
  const translated = source.replace(source.trim(), window.t(source.trim()));
  renderedText.set(node, translated);
  if (current !== translated) node.nodeValue = translated;
}

function translateElement(element) {
  const attributes = ["aria-label", "placeholder", "title"];
  [element, ...element.querySelectorAll("*")].forEach((target) => {
    let sources = sourceAttributes.get(target);
    if (!sources) {
      sources = {};
      sourceAttributes.set(target, sources);
    }
    attributes.forEach((name) => {
      if (!target.hasAttribute(name)) return;
      if (!(name in sources)) sources[name] = target.getAttribute(name);
      target.setAttribute(name, window.t(sources[name]));
    });
  });
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateTextNode(walker.currentNode);
}

function applyLanguage() {
  document.documentElement.lang = currentLanguage;
  document.querySelector("#language-select").value = currentLanguage;
  translateElement(document.body);
  document.dispatchEvent(new CustomEvent("face-language-changed", { detail: currentLanguage }));
}

const observer = new MutationObserver((mutations) => {
  mutations.forEach((mutation) => {
    if (mutation.type === "characterData") translateTextNode(mutation.target);
    mutation.addedNodes.forEach((node) => {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
    });
  });
});

observer.observe(document.body, { childList: true, subtree: true, characterData: true });
document.querySelector("#language-select").addEventListener("change", (event) => {
  currentLanguage = event.target.value;
  localStorage.setItem("face-access-language", currentLanguage);
  applyLanguage();
});
applyLanguage();
